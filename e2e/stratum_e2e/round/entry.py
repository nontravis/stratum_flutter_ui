"""Plans and writes the integration entry files of a device round (design sections 9 and 15).

One entry file per distinct (build mode, entry content) on a platform imports every file the platform runs, so the
platform builds once; a file marked `plain_name` on a target, or named by a sequence on it, runs alone instead. Write a
plan's files (`write_run_file`) right before running it, since two plans may share a wrapped sibling's name.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field, replace
from pathlib import Path
from types import MappingProxyType
from typing import Literal

from stratum_e2e.round.catalog import RunSequence, Target
from stratum_e2e.round.wrap_repeat import dart_string, sibling_path, wrap_file

# An entry sits in `integration_test/` itself, beside the files it imports: a web run roots `org-dartlang-app:///` at
# the entry's own folder (flutter_tools `resident_web_runner.dart`), so an import that climbs above it never resolves.
ENTRY_PREFIX = "dt_round_"
_WRAPPED_PREFIX = ".dt_"
# A file whose name ends in one of these suffixes runs only on the platform it names.
_PLATFORM_ONLY_SUFFIXES = MappingProxyType({
    "_linux_test.dart": ("linux",),
    "_mobile_test.dart": ("android", "ios"),
    "_web_test.dart": ("web",),
})
_TEST_SUFFIX = "_test.dart"
_KEY_HEX_LENGTH = 8

_ENTRY_TEMPLATE = """\
// GENERATED by stratum_e2e.round.entry; never edit. One integration entry for a device round run.
// ignore_for_file: file_names, invalid_use_of_visible_for_testing_member
// ignore_for_file: depend_on_referenced_packages, implementation_imports
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:test_api/src/backend/invoker.dart' show Invoker;
import 'package:test_api/src/backend/state.dart' show Result;

{imports}

void main() {{
  final binding = IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  final round = <String, dynamic>{{}};
  // A test may assign `binding.reportData`; every tearDown puts the round's map back into the map held then.
  void keepRound() => (binding.reportData ??= <String, dynamic>{{}})['stratum_round'] = round;
  keepRound();

{groups}

  tearDownAll(keepRound);
}}
"""

_GROUP_TEMPLATE = """\
  group('{path}', () {{
    final file = <String, String>{{}};
    round['{path}'] = file;
    var held = <String, Object>{{}};
    setUp(() {{
      held = Map<String, Object>.of(binding.results);
      binding.results.clear();
    }});
    tearDown(() {{
      keepRound();
      final current = Map<String, Object>.of(binding.results);
      // The binding keeps 'success' for a `markTestSkipped` and for an error thrown in a test's own tearDown; only
      // the live test's state tells. Precedence: fail, then skip, then pass.
      // Limit: a nested group's setUpAll that fails leaves that group's tests out of this map.
      final state = Invoker.current!.liveTest.state;
      final failed = state.result.isFailing;
      final skipped = state.result == Result.skipped;
      for (final result in current.entries) {{
        if (result.value != 'success' || failed) {{
          file[result.key] = 'fail';
        }} else if (skipped) {{
          file.putIfAbsent(result.key, () => 'skip');
        }} else if (file[result.key] != 'fail') {{
          file[result.key] = 'pass';
        }}
      }}
      binding.results
        ..clear()
        ..addAll(held)
        ..addAll(current)
        ..addAll({{
          for (final result in held.entries)
            if (result.value != 'success') result.key: result.value,
        }});
    }});
    f{index}.main();
  }});"""


@dataclass(frozen=True)
class RunPlan:
    """One run of one entry (or one marked file, or one sequence) that targets share when their plans are equal.

    `wrapped` maps a file to the block prefixes that run `repeat` times as a wrapped sibling; `plain_name` is the
    `--plain-name` text of a `plain_name` run; `sequence` is the `RunSequence.name` of a sequence run, `None` for the
    rest. `key` names the entry file and counts the wrapped block prefixes, so two entries that wrap different blocks
    of one file never share a name.
    """

    key: str
    platform: str
    build_mode: str | None
    kind: Literal["entry", "plain_name", "sequence"]
    files: tuple[str, ...]
    wrapped: Mapping[str, tuple[str, ...]] = field(hash=False)
    repeat: int
    plain_name: str | None = None
    sequence: str | None = None


def platform_files(integration_dir: Path, platform: str) -> list[str]:
    """Returns the sorted paths, relative to `integration_dir`, of the `_test.dart` files `platform` runs.

    A `*_linux_test.dart` file counts on `linux` only, a `*_mobile_test.dart` file on `android` and `ios` only, and a
    `*_web_test.dart` file on `web` only (a `chrome` or `chrome_wasm` target); a round entry and a wrapped sibling
    never count.
    """
    found: list[str] = []
    for path in integration_dir.rglob(f"*{_TEST_SUFFIX}"):
        relative = path.relative_to(integration_dir)
        hidden = any(part.startswith(".") for part in relative.parts)
        if hidden or relative.name.startswith(ENTRY_PREFIX) or not path.is_file():
            continue
        if not _runs_on(relative.name, platform):
            continue
        found.append(relative.as_posix())
    return sorted(found)


def _runs_on(name: str, platform: str) -> bool:
    return all(
        platform in only for suffix, only in _PLATFORM_ONLY_SUFFIXES.items() if name.endswith(suffix)
    )


def plan_runs(
    platform: str,
    targets: Sequence[Target],
    files: Sequence[str],
    sequences: Sequence[RunSequence],
    repeat: int,
) -> dict[str, list[RunPlan]]:
    """Returns, per target name, the runs of one round: its entry, then its `plain_name` runs, then its sequences.

    Raises `ValueError` when `repeat` is below 1, a target belongs to another platform, a target marks a file the
    platform does not run, or a target marks one file for both a repeat wrap and a `plain_name` or sequence run.
    """
    if repeat < 1:
        raise ValueError(f"repeat must be at least 1, got {repeat}")
    shared: dict[RunPlan, RunPlan] = {}
    plans: dict[str, list[RunPlan]] = {}
    for target in targets:
        if target.platform != platform:
            raise ValueError(f"target {target.name} runs on {target.platform}, not {platform}")
        plans[target.name] = [
            shared.setdefault(plan, plan) for plan in _target_plans(platform, target, files, sequences, repeat)
        ]
    return plans


def entry_source(plan: RunPlan) -> str:
    """Returns the Dart text of `plan`'s entry: each file as a group named by its path, with a per-file result map."""
    imports = "\n".join(
        f"import '{_import_path(plan, relative)}' as f{index};" for index, relative in enumerate(plan.files)
    )
    groups = "\n".join(
        _GROUP_TEMPLATE.format(path=dart_string(relative), index=index) for index, relative in enumerate(plan.files)
    )
    return _ENTRY_TEMPLATE.format(imports=imports, groups=groups)


def write_run_file(plan: RunPlan, integration_dir: Path) -> Path:
    """Writes `plan`'s wrapped siblings and its entry (`<ENTRY_PREFIX><platform>_<key>_test.dart` in
    `integration_dir` itself) under `integration_dir`, and returns the entry's path.

    Raises `ValueError` for a sequence: its files run directly, one launch each, never through an entry.
    """
    if plan.kind == "sequence":
        raise ValueError(f"a sequence runs its files directly and has no entry file: {', '.join(plan.files)}")
    for relative, prefixes in plan.wrapped.items():
        wrap_file(integration_dir / relative, prefixes, plan.repeat)
    entry = integration_dir / f"{ENTRY_PREFIX}{plan.platform}_{plan.key}{_TEST_SUFFIX}"
    entry.write_text(entry_source(plan), encoding="utf-8")
    return entry


def cleanup(integration_dir: Path) -> None:
    """Removes every round entry and wrapped sibling under `integration_dir`."""
    for generated in (*integration_dir.glob(f"{ENTRY_PREFIX}*"), *integration_dir.rglob(f"{_WRAPPED_PREFIX}*")):
        if generated.is_file():
            generated.unlink()


def _target_plans(
    platform: str,
    target: Target,
    files: Sequence[str],
    sequences: Sequence[RunSequence],
    repeat: int,
) -> list[RunPlan]:
    own_sequences = [sequence for sequence in sequences if sequence.target == target.name]
    alone = {*target.plain_name, *(file for sequence in own_sequences for file in sequence.files)}
    missing = sorted({*alone, *target.repeat} - set(files))
    if missing:
        raise ValueError(f"target {target.name} marks {', '.join(missing)}, which {platform} does not run")

    clash = sorted(alone & set(target.repeat))
    if clash:
        raise ValueError(f"target {target.name} repeats {', '.join(clash)}, which it also runs alone")

    def build(
        kind: Literal["entry", "plain_name", "sequence"],
        run_files: tuple[str, ...],
        wrapped: Mapping[str, tuple[str, ...]],
        plain_name: str | None = None,
        sequence: str | None = None,
    ) -> RunPlan:
        draft = RunPlan(
            key="", platform=platform, build_mode=target.build_mode, kind=kind, files=run_files,
            wrapped=MappingProxyType(dict(wrapped)), repeat=repeat, plain_name=plain_name, sequence=sequence,
        )
        return replace(draft, key=f"{target.build_mode or 'none'}-{_digest(draft)}")

    in_entry = tuple(file for file in files if file not in alone)
    wrapped = {file: prefixes for file, prefixes in target.repeat.items() if file in in_entry} if repeat > 1 else {}
    runs = [build("entry", in_entry, wrapped)] if in_entry else []
    runs += [build("plain_name", (file,), {}, name) for file, name in target.plain_name.items()]
    runs += [build("sequence", sequence.files, {}, sequence=sequence.name) for sequence in own_sequences]
    return runs


def _digest(plan: RunPlan) -> str:
    """Returns the first hex digits of the sha1 over the entry source and the wrapped blocks' prefixes.

    The siblings' text is the source files' text with these prefixes wrapped, and no source file is read at planning
    time, so the prefixes stand for it.
    """
    wrapped = "".join(f"\n{relative}\0{'\0'.join(prefixes)}" for relative, prefixes in sorted(plan.wrapped.items()))
    return hashlib.sha1((entry_source(plan) + wrapped).encode("utf-8"), usedforsecurity=False).hexdigest()[
        :_KEY_HEX_LENGTH
    ]


def _import_path(plan: RunPlan, relative: str) -> str:
    if relative not in plan.wrapped:
        return relative
    return sibling_path(Path(relative), plan.repeat).as_posix()
