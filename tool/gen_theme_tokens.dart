// Generates lib/src/themes/tokens/theme_tokens.g.dart from the package
// default theme.yaml. Run from the package root after every edit of the
// default theme's token keys, then commit the output:
//
//   dart run tool/gen_theme_tokens.dart
import 'dart:io';

import 'package:stratum_ui/src/themes/config/transparent.dart';
import 'package:stratum_ui/src/themes/constant/color.dart';
import 'package:yaml/yaml.dart';

/// The yaml the generator reads, from the package root.
const themePath = 'assets/themes/default/theme.yaml';

/// The file the generator writes, from the package root.
const tokensPath = 'lib/src/themes/tokens/theme_tokens.g.dart';

/// The first line of the generated file.
const generatedHeader =
    '// GENERATED by tool/gen_theme_tokens.dart from '
    'assets/themes/default/theme.yaml. Do not edit.';

const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', //
  'finally', 'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', //
  'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'var', //
  'void', 'while', 'with',
};

final _digits = RegExp(r'^\d+$');
final _digitsThenLetters = RegExp(r'^(\d+)([a-z]+)$');

/// The Dart name of one yaml key [segment] at [path] (spec section 6.2).
///
/// [digitPrefix] is `c` inside a palette ramp and `p` inside a
/// `transparent` group; a digits-only first part elsewhere stops the
/// generator, as does any other digit-led first part.
String dartName(String segment, {required String path, String? digitPrefix}) {
  final parts = segment.split('-');
  final first = parts.first;
  if (_digits.hasMatch(first)) {
    if (digitPrefix == null) {
      throw FormatException('$path: a digit-led key needs a ramp or step');
    }
    parts[0] = '$digitPrefix$first';
  } else if (_digitsThenLetters.firstMatch(first) case final match?) {
    parts[0] = '${match[2]}${match[1]}';
  } else if (first.startsWith(RegExp('[0-9]'))) {
    throw FormatException('$path: a digit-led key needs a ramp or step');
  }
  final name = [
    parts.first,
    for (final part in parts.skip(1))
      if (part.isNotEmpty) '${part[0].toUpperCase()}${part.substring(1)}',
  ].join();
  return _reserved.contains(name) ? '${name}s' : name;
}

String _pascal(String name) => '${name[0].toUpperCase()}${name.substring(1)}';

/// The Dart names of [keys] at [path], in order; stops on two keys that
/// give one name (spec section 6.2 rule 8).
Map<String, String> _names(
  Iterable<String> keys,
  String path, {
  String? digitPrefix,
}) {
  final byName = <String, String>{};
  final result = <String, String>{};
  for (final key in keys) {
    final keyPath = path.isEmpty ? key : '$path.$key';
    final name = dartName(key, path: keyPath, digitPrefix: digitPrefix);
    if (byName[name] case final other?) {
      throw FormatException('$other and $keyPath both give the name $name');
    }
    byName[name] = keyPath;
    result[key] = name;
  }
  return result;
}

Map<String, Object?> _map(Object? node, String path) {
  if (node is! YamlMap) throw FormatException('$path: expected a map');
  return {for (final MapEntry(:key, :value) in node.entries) '$key': value};
}

/// The source of `lib/src/themes/tokens/theme_tokens.g.dart` for the
/// package default [yaml] (spec section 6): reads keys only, never values.
String generateThemeTokens(String yaml) {
  final root = _map(loadYaml(yaml), '(root)');
  final out = StringBuffer()
    ..writeln(generatedHeader)
    ..writeln()
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln("import 'package:stratum_ui/src/themes/config/theme_asset.dart';")
    ..writeln("import 'package:stratum_ui/src/themes/constant/color.dart';")
    ..writeln()
    ..writeln(
      '/// A `<group>.color` group that gives its token for a [ColorEnum] '
      'name.',
    )
    ..writeln('abstract interface class StratumColorEnumTokens {')
    ..writeln('  /// The token named [color]; null when this group holds none.')
    ..writeln('  Color? operator [](ColorEnum color);')
    ..writeln('}');
  final light = _map(_map(root['color'], 'color')['light'], 'color.light')
    ..remove('app');
  _colorClass(out, light, const []);
  _palette(out, _map(root['palette'], 'palette')..remove('app'));
  _transparent(out);
  for (final group in const ['space', 'radius', 'layouts']) {
    _dimensions(out, group, _map(root[group], group).keys);
  }
  _assets(out, _map(root['assets'], 'assets').keys);
  out
    ..writeln()
    ..writeln('Color _color(Map<String, Color> colors, String path) =>')
    ..writeln('    colors[path] ??')
    ..writeln('    (throw ArgumentError.value(')
    ..writeln('      path,')
    ..writeln("      'path',")
    ..writeln("      'no color at this path in the theme config',")
    ..writeln('    ));');
  return out.toString();
}

String _colorClassName(List<String> dartPath) =>
    'StratumColor${dartPath.map(_pascal).join()}Tokens';

void _colorClass(
  StringBuffer out,
  Map<String, Object?> node,
  List<(String, String)> path,
) {
  final yamlPath = path.map((entry) => entry.$1).join('.');
  final dartPath = [for (final (_, name) in path) name];
  final className = _colorClassName(dartPath);
  final inTransparent = path.length == 1 && path.single.$1 == 'transparent';
  // A `<group>.color` class (spec FO-03 s03 invariant 33): the one depth
  // whose classes hold the colors named after the palette.
  final answersColorEnum = path.length == 2 && path.last.$1 == 'color';
  final names = _names(
    node.keys,
    yamlPath,
    digitPrefix: inTransparent ? 'p' : null,
  );
  final children = <String>[];
  out
    ..writeln()
    ..writeln(
      path.isEmpty
          ? '/// The colors of one color set, `color.<set>` without `app`.'
          : '/// The `$yamlPath` group of each color set.',
    )
    ..writeln(
      'final class $className'
      '${answersColorEnum ? ' implements StratumColorEnumTokens' : ''} {',
    )
    ..writeln(
      path.isEmpty
          ? '  $className.fromMap(Map<String, Color> colors)'
          : '  $className._(Map<String, Color> colors)',
    );
  final entries = node.entries.toList();
  for (final (index, MapEntry(:key, :value)) in entries.indexed) {
    final keyPath = yamlPath.isEmpty ? key : '$yamlPath.$key';
    final name = names[key]!;
    final lead = index == 0 ? '    : ' : '      ';
    final end = index == entries.length - 1 ? ';' : ',';
    if (value is YamlMap) {
      final child = _colorClassName([...dartPath, name]);
      children.add(key);
      out.writeln('$lead$name = $child._(colors)$end');
    } else {
      out.writeln("$lead$name = _color(colors, '$keyPath')$end");
    }
  }
  for (final MapEntry(:key, :value) in node.entries) {
    final keyPath = yamlPath.isEmpty ? key : '$yamlPath.$key';
    final name = names[key]!;
    final type = value is YamlMap
        ? _colorClassName([...dartPath, name])
        : 'Color';
    out
      ..writeln()
      ..writeln('  /// `$keyPath`')
      ..writeln('  final $type $name;');
  }
  if (answersColorEnum) _colorEnumLookup(out, node, names);
  out.writeln('}');
  for (final key in children) {
    _colorClass(out, _map(node[key], key), [...path, (key, names[key]!)]);
  }
}

/// The `operator []` of a `<group>.color` class (spec FO-03 s03
/// invariant 33): one case per [ColorEnum] value, in enum order, whose
/// name is the Dart name of a color of [node]; null for every other name.
/// A semantic key such as `negative` is no [ColorEnum] name, so it never
/// matches.
void _colorEnumLookup(
  StringBuffer out,
  Map<String, Object?> node,
  Map<String, String> names,
) {
  final colors = {
    for (final MapEntry(:key, :value) in node.entries)
      if (value is! YamlMap) names[key]!,
  };
  final held = [
    for (final color in ColorEnum.values)
      if (colors.contains(color.name)) color.name,
  ];
  out
    ..writeln()
    ..writeln('  @override');
  if (held.isEmpty) {
    out.writeln('  Color? operator [](ColorEnum color) => null;');
    return;
  }
  out.writeln('  Color? operator [](ColorEnum color) => switch (color) {');
  for (final name in held) {
    out.writeln('    ColorEnum.$name => $name,');
  }
  if (held.length < ColorEnum.values.length) out.writeln('    _ => null,');
  out.writeln('  };');
}

void _palette(StringBuffer out, Map<String, Object?> ramps) {
  final names = _names(ramps.keys, 'palette');
  final shades = <String>{};
  for (final MapEntry(:key, :value) in ramps.entries) {
    final keys = _map(value, 'palette.$key').keys.toList();
    if (shades.isEmpty) shades.addAll(keys);
    if (keys.join(',') != shades.join(',')) {
      throw FormatException('palette.$key: every ramp needs the same shades');
    }
  }
  final shadeNames = _names(shades, 'palette.<ramp>', digitPrefix: 'c');
  out
    ..writeln()
    ..writeln('/// The ramps of `palette`, without `app`.')
    ..writeln('final class StratumPaletteTokens {')
    ..writeln('  StratumPaletteTokens.fromMap(Map<String, Color> palette)');
  _initializers(out, [
    for (final MapEntry(:key, value: name) in names.entries)
      "$name = StratumPaletteRamp._(palette, '$key')",
  ]);
  for (final MapEntry(:key, value: name) in names.entries) {
    out
      ..writeln()
      ..writeln('  /// `palette.$key`')
      ..writeln('  final StratumPaletteRamp $name;');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// One shared class: every ramp of the package default has the same '
      '${shades.length} shades.',
    )
    ..writeln('final class StratumPaletteRamp {')
    ..writeln(
      '  StratumPaletteRamp._(Map<String, Color> palette, String ramp)',
    );
  _initializers(out, [
    for (final MapEntry(:key, value: name) in shadeNames.entries)
      "$name = _color(palette, '\$ramp.$key')",
  ]);
  for (final MapEntry(:key, value: name) in shadeNames.entries) {
    out
      ..writeln()
      ..writeln('  /// Shade `$key`')
      ..writeln('  final Color $name;');
  }
  out.writeln('}');
}

void _transparent(StringBuffer out) {
  final ramps = _names(transparentColors.keys, 'transparent');
  final steps = transparentColors.values.first.keys.toList();
  for (final MapEntry(:key, :value) in transparentColors.entries) {
    if (value.keys.join(',') != steps.join(',')) {
      throw FormatException(
        'transparent.$key: every ramp needs the same steps',
      );
    }
  }
  final stepNames = _names(steps, 'transparent.<ramp>', digitPrefix: 'p');
  out
    ..writeln()
    ..writeln(
      '/// The built-in steps `transparent.black` and '
      '`transparent.white`.',
    )
    ..writeln('final class StratumTransparentTokens {')
    ..writeln(
      '  const StratumTransparentTokens._({'
      '${[for (final name in ramps.values) 'required this.$name'].join(', ')}'
      '});',
    )
    ..writeln()
    ..writeln(
      '  /// The ${ramps.length * steps.length} built-in steps of '
      '`transparentColors`, as constants.',
    )
    ..writeln('  static const builtIn = StratumTransparentTokens._(');
  for (final MapEntry(:key, value: name) in ramps.entries) {
    out.writeln('    $name: StratumTransparentRamp._(');
    for (final MapEntry(key: step, value: stepName) in stepNames.entries) {
      out.writeln(
        '      $stepName: Color(${_argb(transparentColors[key]![step]!)}),',
      );
    }
    out.writeln('    ),');
  }
  out.writeln('  );');
  for (final MapEntry(:key, value: name) in ramps.entries) {
    out
      ..writeln()
      ..writeln('  /// `transparent.$key`')
      ..writeln('  final StratumTransparentRamp $name;');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// One shared class: every built-in ramp has the same '
      '${steps.length} steps.',
    )
    ..writeln('final class StratumTransparentRamp {')
    ..writeln('  const StratumTransparentRamp._({');
  for (final name in stepNames.values) {
    out.writeln('    required this.$name,');
  }
  out.writeln('  });');
  for (final MapEntry(:key, value: name) in stepNames.entries) {
    out
      ..writeln()
      ..writeln('  /// Step `$key`')
      ..writeln('  final Color $name;');
  }
  out.writeln('}');
}

/// `#RRGGBBAA` as the Dart literal `0xAARRGGBB`.
String _argb(String hex) => '0x${hex.substring(7, 9)}${hex.substring(1, 7)}'
    .toUpperCase()
    .replaceFirst('0X', '0x');

void _dimensions(StringBuffer out, String group, Iterable<String> keys) {
  final className =
      'Stratum${_pascal(group == 'layouts' ? 'layout' : group)}'
      'Tokens';
  final names = _names(keys, group);
  out
    ..writeln()
    ..writeln(
      '/// The `$group` tokens in logical pixels for the current window '
      'size.',
    )
    ..writeln('final class $className {')
    ..writeln('  $className(this._read);')
    ..writeln()
    ..writeln('  final double Function(String name) _read;');
  for (final MapEntry(:key, value: name) in names.entries) {
    out
      ..writeln()
      ..writeln('  /// `$group.$key`')
      ..writeln("  double get $name => _read('$key');");
  }
  out.writeln('}');
}

void _assets(StringBuffer out, Iterable<String> slots) {
  final names = _names(slots, 'assets');
  out
    ..writeln()
    ..writeln('/// The asset slots of `assets`.')
    ..writeln('final class StratumAssetTokens {')
    ..writeln(
      '  StratumAssetTokens.fromMap(Map<String, StratumThemeAsset> assets)',
    );
  _initializers(out, [
    for (final MapEntry(:key, value: name) in names.entries)
      "$name = assets['$key']",
  ]);
  for (final MapEntry(:key, value: name) in names.entries) {
    out
      ..writeln()
      ..writeln('  /// `assets.$key`; null when the slot is empty.')
      ..writeln('  final StratumThemeAsset? $name;');
  }
  out.writeln('}');
}

void _initializers(StringBuffer out, List<String> lines) {
  for (final (index, line) in lines.indexed) {
    final lead = index == 0 ? '    : ' : '      ';
    final end = index == lines.length - 1 ? ';' : ',';
    out.writeln('$lead$line$end');
  }
}

void main(List<String> arguments) {
  final output = arguments.isEmpty ? tokensPath : arguments.single;
  File(output)
    ..createSync(recursive: true)
    ..writeAsStringSync(
      generateThemeTokens(File(themePath).readAsStringSync()),
    );
  stdout.writeln('Wrote $output');
}
