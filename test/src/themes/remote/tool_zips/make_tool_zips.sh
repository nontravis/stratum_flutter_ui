#!/usr/bin/env bash
# Zips one theme folder with each real zip tool the remote theme install
# must accept (FO-04 US-01 FR-02 E02, E13; design RZ3) and writes the
# zips, base64, into tool_zips.g.dart beside this script, so a test reads
# them on the VM and on Chrome alike.
#
# Usage: test/src/themes/remote/tool_zips/make_tool_zips.sh
# Needs: macOS (ditto, xattr, sw_vers), Info-ZIP zip and unzip, Java 16 or
# later, 7-Zip (7zz), python3. Exit 69 when a tool is missing.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for tool in ditto xattr sw_vers zip unzip java 7zz python3; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "make_tool_zips: $tool not found" >&2
    exit 69
  fi
done

src="$work/src"
mkdir -p "$src/brand/images"
# shellcheck disable=SC2016 # literal YAML content, not an unexpanded variable
printf '%s\n' '$schema: stratum-theme/v1.0.0' 'assets:' \
  '  loading: images/logo.svg' >"$src/brand/theme.yaml"
printf '%s' '<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4"/>' \
  >"$src/brand/images/logo.svg"
# An extended attribute makes ditto write an AppleDouble entry under
# __MACOSX/, as Finder's Compress does.
xattr -w com.apple.metadata:kMDItemComment stratum \
  "$src/brand/images/logo.svg"

(cd "$src" && ditto -c -k --sequesterRsrc --keepParent brand "$work/finder.zip")
(cd "$src" && zip -q -r "$work/infozip.zip" brand)

cat >"$work/MakeZip.java" <<'JAVA'
import java.io.FileOutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/** Zips one folder, folder entries included, at the given deflate level. */
public class MakeZip {
  public static void main(String[] args) throws Exception {
    Path root = Path.of(args[0]);
    int level = Integer.parseInt(args[2]);
    List<Path> paths;
    try (Stream<Path> walk = Files.walk(root)) {
      paths = walk.sorted().toList();
    }
    try (ZipOutputStream zip =
        new ZipOutputStream(new FileOutputStream(args[1]))) {
      zip.setLevel(level);
      for (Path path : paths) {
        String name =
            root.getParent().relativize(path).toString().replace('\\', '/');
        if (Files.isDirectory(path)) {
          zip.putNextEntry(new ZipEntry(name + "/"));
        } else {
          zip.putNextEntry(new ZipEntry(name));
          zip.write(Files.readAllBytes(path));
        }
        zip.closeEntry();
      }
    }
  }
}
JAVA
java "$work/MakeZip.java" "$src/brand" "$work/java-level0.zip" 0
java "$work/MakeZip.java" "$src/brand" "$work/java-default.zip" -1
# 7-Zip at each setting the follow-ups design measured (FU1, RZF1).
(cd "$src" && 7zz a -tzip -mx=5 -bso0 -bsp0 "$work/7zip-mx5.zip" brand)
(cd "$src" && 7zz a -tzip -mx=7 -bso0 -bsp0 "$work/7zip-mx7.zip" brand)
(cd "$src" && 7zz a -tzip -mx=9 -bso0 -bsp0 "$work/7zip-mx9.zip" brand)
(cd "$src" && 7zz a -tzip -mx=9 -mpass=15 -mfb=258 -bso0 -bsp0 \
  "$work/7zip-mx9-pass15-fb258.zip" brand)

for zip in finder infozip java-level0 java-default 7zip-mx5 7zip-mx7 \
  7zip-mx9 7zip-mx9-pass15-fb258; do
  unzip -tq "$work/$zip.zip" >/dev/null
  echo "$zip.zip: $(unzip -Z1 "$work/$zip.zip" | tr '\n' ' ')"
done

python3 -I - "$work" "$here/tool_zips.g.dart" \
  "$(sw_vers -productVersion)" "$(zip -v | sed -n 2p | sed 's/^ *//')" \
  "$(java -version 2>&1 | head -1)" "$(7zz | sed -n 2p | sed 's/ :.*//')" <<'PY'
import base64
import sys

work, out, macos, infozip, java, sevenzip = sys.argv[1:7]
zips = [
    ('finder', 'finder.zip'),
    ('infoZip', 'infozip.zip'),
    ('javaLevel0', 'java-level0.zip'),
    ('javaDefault', 'java-default.zip'),
    ('sevenZipMx5', '7zip-mx5.zip'),
    ('sevenZipMx7', '7zip-mx7.zip'),
    ('sevenZipMx9', '7zip-mx9.zip'),
    ('sevenZipMx9Pass15Fb258', '7zip-mx9-pass15-fb258.zip'),
]
lines = [
    '// GENERATED by make_tool_zips.sh; do not edit. Run the script to',
    '// rebuild it.',
    f'// macOS {macos} ditto; {infozip}; {java}; {sevenzip}.',
    '',
    '/// Each real-tool zip of one theme folder, `brand/` holding',
    '/// `theme.yaml` and `images/logo.svg`, base64-encoded so a Chrome',
    '/// test reads it too.',
    'const toolZips = <String, String>{',
]
for key, name in zips:
    with open(f'{work}/{name}', 'rb') as zip_file:
        data = base64.b64encode(zip_file.read()).decode()
    chunks = [data[i:i + 64] for i in range(0, len(data), 64)]
    lines.append(f"  '{key}':")
    for index, chunk in enumerate(chunks):
        comma = ',' if index == len(chunks) - 1 else ''
        lines.append(f"      '{chunk}'{comma}")
lines.append('};')
with open(out, 'w') as dart_file:
    dart_file.write('\n'.join(lines) + '\n')
PY
echo "wrote $here/tool_zips.g.dart"
