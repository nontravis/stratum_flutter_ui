@TestOn('vm')
library;

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:stratum_ui/src/themes/remote/generated/google_font_names.g.dart';
import 'package:yaml/yaml.dart';

const _path = 'lib/src/themes/remote/generated/google_font_names.g.dart';
const _update = bool.fromEnvironment('UPDATE_GOOGLE_FONT_NAMES');

String _quote(String name) {
  final escaped = name
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}

/// The version of google_fonts this package resolves: the `version:` of
/// that package's own pubspec, found through
/// `.dart_tool/package_config.json`.
String _resolvedGoogleFontsVersion() {
  final config = File('.dart_tool/package_config.json').absolute;
  if (!config.existsSync()) {
    fail('${config.path} is missing: run flutter pub get first');
  }
  final json = jsonDecode(config.readAsStringSync()) as Map<String, Object?>;
  final packages = (json['packages']! as List<Object?>)
      .cast<Map<String, Object?>>();
  Map<String, Object?>? package;
  for (final entry in packages) {
    if (entry['name'] == 'google_fonts') {
      package = entry;
      break;
    }
  }
  if (package == null) {
    fail(
      'google_fonts is missing from ${config.path}: run flutter pub get '
      'first',
    );
  }
  final rootUri = package['rootUri']! as String;
  final root = config.uri.resolve(
    rootUri.endsWith('/') ? rootUri : '$rootUri/',
  );
  final pubspec = loadYaml(
    File.fromUri(root.resolve('pubspec.yaml')).readAsStringSync(),
  ) as YamlMap;
  return pubspec['version']! as String;
}

String _source(List<String> names, String version) => [
  '// GENERATED by test/src/themes/remote/google_font_names_test.dart',
  '// from GoogleFonts.asMap() of google_fonts $version. Do not edit.',
  '// To move to another google_fonts version, set both bounds of its',
  '// pubspec.yaml constraint to it, then run that test with',
  '// --dart-define=UPDATE_GOOGLE_FONT_NAMES=true.',
  '',
  '/// The google_fonts version [googleFontNames] was generated from. The',
  '/// test fails when the package resolves another version (FO-04 s03',
  '/// INV-17).',
  "const googleFontNamesVersion = '$version';",
  '',
  '/// Every family name of `GoogleFonts.asMap()`, for the Flutter-free',
  '/// install check of the `stratum_theme` CLI (FO-04 US-02 FR-02), which',
  '/// cannot load google_fonts (plan D-j).',
  'const googleFontNames = <String>{',
  for (final name in names) '  ${_quote(name)},',
  '};',
  '',
].join('\n');

void main() {
  test(
    'oq-c, fo04/us02/fr02/e07: googleFontNames is GoogleFonts.asMap() of the '
    'google_fonts this package resolves',
    () {
      final names = GoogleFonts.asMap().keys.toList()..sort();
      if (_update) {
        File(_path)
            .writeAsStringSync(_source(names, _resolvedGoogleFontsVersion()));
        return;
      }
      expect(
        googleFontNames.toList()..sort(),
        names,
        reason: 'regenerate: see the header of $_path',
      );
    },
  );

  test('r12, fo04/us02/fr02/e09, s03/inv17: the list records the google_fonts '
      'version it came from, and the package resolves that version', () {
    expect(
      _resolvedGoogleFontsVersion(),
      googleFontNamesVersion,
      reason: 'regenerate: see the header of $_path',
    );
  }, skip: _update ? 'regenerating the list' : false);

  test('r12, s03/inv17: pubspec.yaml allows only the recorded google_fonts '
      'version', () {
    final pubspec =
        loadYaml(File('pubspec.yaml').readAsStringSync()) as YamlMap;
    final dependencies = pubspec['dependencies']! as YamlMap;

    expect(dependencies['google_fonts'], googleFontNamesVersion);
  }, skip: _update ? 'regenerating the list' : false);
}
