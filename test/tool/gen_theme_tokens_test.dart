import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:stratum_ui/src/src.dart';
import 'package:stratum_ui/src/themes/config/transparent.dart';

import '../../tool/gen_theme_tokens.dart';

/// The smallest yaml the generator reads, with [space] as its space group.
String _yaml(String space) =>
    '''
color:
  light:
    brand: { normal: "#000000" }
palette:
  brand: { 500: "#000000" }
space:
$space
radius: { md: 10 }
layouts: { max-width-read: 720 }
assets: { loading: }
opacity: { disabled: 0.5 }
''';

/// `#RRGGBBAA` as the Dart color `0xAARRGGBB`.
Color _color(String hex) =>
    Color(int.parse('${hex.substring(7, 9)}${hex.substring(1, 7)}', radix: 16));

void main() {
  test('the committed file equals the generator output', () {
    final generated = generateThemeTokens(File(themePath).readAsStringSync());
    final committed = File(tokensPath).readAsStringSync();

    expect(
      committed == generated,
      isTrue,
      reason: 'run dart run tool/gen_theme_tokens.dart and commit the result',
    );
  });

  test('the output starts with the generated header', () {
    final generated = generateThemeTokens(File(themePath).readAsStringSync());

    expect(generated.split('\n').first, generatedHeader);
    expect(
      generatedHeader,
      '// GENERATED by tool/gen_theme_tokens.dart from '
      'assets/themes/default/theme.yaml. Do not edit.',
    );
  });

  group('dartName', () {
    final cases = <(String, String, String?, String)>[
      (
        'primary-on-color',
        'text.default.primary-on-color',
        null,
        'primaryOnColor',
      ),
      ('default', 'text.default', null, 'defaults'),
      ('500', 'palette.brand.500', 'c', 'c500'),
      ('3', 'transparent.black.3', 'p', 'p3'),
      ('3-inverse', 'color.light.transparent.3-inverse', 'p', 'p3Inverse'),
      ('2xs', 'space.2xs', null, 'xs2'),
      ('5xl', 'radius.5xl', null, 'xl5'),
      ('10xl', 'space.10xl', null, 'xl10'),
      (
        'max-width-content',
        'layouts.max-width-content',
        null,
        'maxWidthContent',
      ),
      (
        'rating-emoji-parts',
        'misc.rating-emoji-parts',
        null,
        'ratingEmojiParts',
      ),
      ('class', 'misc.class', null, 'classs'),
    ];
    for (final (segment, path, prefix, expected) in cases) {
      test('$path gives $expected', () {
        expect(dartName(segment, path: path, digitPrefix: prefix), expected);
      });
    }

    test('a digit-led key outside a ramp or step stops the generator', () {
      expect(
        () => dartName('3', path: 'space.3'),
        throwsA(
          isA<FormatException>().having(
            (error) => error.message,
            'message',
            contains('space.3'),
          ),
        ),
      );
      expect(
        () => dartName('3D', path: 'misc.3D'),
        throwsA(isA<FormatException>()),
      );
    });
  });

  group('generateThemeTokens', () {
    test('two keys that give one name stop it, naming both paths', () {
      expect(
        () => generateThemeTokens(_yaml('  md-x: 1\n  mdX: 2')),
        throwsA(
          isA<FormatException>().having(
            (error) => error.message,
            'message',
            'space.md-x and space.mdX both give the name mdX',
          ),
        ),
      );
    });

    test('a digit-led space key stops it', () {
      expect(
        () => generateThemeTokens(_yaml('  3: 1')),
        throwsA(isA<FormatException>()),
      );
    });

    test('the package default gives the 39 classes of spec section 6.3 and the '
        'opacity class', () {
      final generated = generateThemeTokens(File(themePath).readAsStringSync());
      final names = RegExp(
        r'^final class (\w+)',
        multiLine: true,
      ).allMatches(generated).map((match) => match[1]!).toList();

      expect(names, hasLength(39));
      expect(
        names.where((name) => name.startsWith('StratumColor')),
        hasLength(30),
      );
      expect(names.skip(30), [
        'StratumPaletteTokens',
        'StratumPaletteRamp',
        'StratumTransparentTokens',
        'StratumTransparentRamp',
        'StratumSpaceTokens',
        'StratumRadiusTokens',
        'StratumLayoutTokens',
        'StratumAssetTokens',
        'StratumOpacityTokens',
      ]);
      expect(names, contains('StratumColorTextDefaultsTokens'));
      expect(names, contains('StratumColorBackgroundDefaultsTokens'));
    });
  });

  test('StratumTransparentTokens.builtIn equals transparentColors', () {
    const builtIn = StratumTransparentTokens.builtIn;
    final generated = File(tokensPath).readAsStringSync();

    for (final MapEntry(key: ramp, value: steps) in transparentColors.entries) {
      for (final MapEntry(key: step, value: hex) in steps.entries) {
        final argb = _color(hex).toARGB32().toRadixString(16).toUpperCase();
        expect(
          generated,
          contains('p$step: Color(0x${argb.padLeft(8, '0')}),'),
          reason: 'transparent.$ramp.$step',
        );
      }
    }
    expect(builtIn.black.p3, _color('#00000008'));
    expect(builtIn.white.p100, _color('#FFFFFFFF'));
    expect(builtIn.black.p0, const Color(0x00000000));
  });

  test('fo01/us01/fr01: StratumOpacityTokens reads opacity.disabled', () {
    expect(StratumOpacityTokens.fromMap(const {'disabled': 0.3}).disabled, 0.3);
    expect(
      () => StratumOpacityTokens.fromMap(const {}),
      throwsA(
        isA<ArgumentError>().having(
          (error) => error.invalidValue,
          'invalidValue',
          'disabled',
        ),
      ),
    );
  });

  test('the opacity class takes its keys from the yaml', () {
    final generated = generateThemeTokens(_yaml('  md: 1'));

    expect(generated, contains('final class StratumOpacityTokens {'));
    expect(generated, contains("disabled = _opacity(opacity, 'disabled');"));
    expect(generated, contains('  final double disabled;'));
  });
}
